#!/usr/bin/env python3
"""Splitter-closure audit for arrow-erased Minkowski causal sets.

A graph module is exactly a vertex set with no splitter.  Starting from a pair
{x,y}, repeatedly add every outside vertex adjacent to some but not all current
members.  The fixed point is the unique minimal module containing {x,y}.

For a connected comparability graph C:
    C is UPO iff the minimal module generated by every edge is all of C.

For a general nonempty comparability graph:
    it is UPO iff there is exactly one edge-containing connected component and
    that component satisfies the connected criterion above.

The script validates this criterion on all random-2-orders through a requested
small n and audits the size of proper edge-generated modules in Minkowski
sprinklings.
"""

from __future__ import annotations

import argparse
import itertools
import math
from collections import Counter
from dataclasses import dataclass

import numpy as np


def sprinkle_diamond(n: int, d: int, rng: np.random.Generator) -> np.ndarray:
    spatial_dim = d - 1
    abs_t = 1.0 - rng.random(n) ** (1.0 / d)
    signs = np.where(rng.random(n) < 0.5, -1.0, 1.0)
    t = abs_t * signs

    direction = rng.normal(size=(n, spatial_dim))
    norm = np.linalg.norm(direction, axis=1)
    zero = norm == 0.0
    while np.any(zero):
        direction[zero] = rng.normal(size=(int(np.sum(zero)), spatial_dim))
        norm = np.linalg.norm(direction, axis=1)
        zero = norm == 0.0

    radius = (1.0 - abs_t) * rng.random(n) ** (1.0 / spatial_dim)
    spatial = direction / norm[:, None] * radius[:, None]
    return np.concatenate([t[:, None], spatial], axis=1)


def comparability_masks(points: np.ndarray) -> list[int]:
    n = len(points)
    adj = [0] * n
    for i in range(n):
        dt = points[i + 1 :, 0] - points[i, 0]
        dr2 = np.sum((points[i + 1 :, 1 :] - points[i, 1 :]) ** 2, axis=1)
        causal = np.nonzero(dt * dt > dr2)[0] + i + 1
        for j0 in causal:
            j = int(j0)
            adj[i] |= 1 << j
            adj[j] |= 1 << i
    return adj


def permutation_graph(p: tuple[int, ...]) -> list[int]:
    n = len(p)
    adj = [0] * n
    for i in range(n):
        for j in range(i + 1, n):
            if p[i] < p[j]:
                adj[i] |= 1 << j
                adj[j] |= 1 << i
    return adj


def connected_components(adj: list[int]) -> list[int]:
    n = len(adj)
    unseen = (1 << n) - 1
    components: list[int] = []

    while unseen:
        seed = unseen & -unseen
        component = seed
        frontier = seed
        unseen ^= seed

        while frontier:
            neighbours = 0
            work = frontier
            while work:
                bit = work & -work
                v = bit.bit_length() - 1
                work -= bit
                neighbours |= adj[v]

            new = neighbours & unseen
            if not new:
                break
            component |= new
            unseen ^= new
            frontier = new

        components.append(component)

    return components


def minimal_module_closure(
    adj: list[int],
    u: int,
    v: int,
    universe: int,
) -> int:
    """Return the unique minimal module in universe containing u and v."""
    current = (1 << u) | (1 << v)

    while True:
        size = current.bit_count()
        splitters = 0
        outside = universe & ~current

        work = outside
        while work:
            bit = work & -work
            z = bit.bit_length() - 1
            work -= bit

            hits = (adj[z] & current).bit_count()
            if 0 < hits < size:
                splitters |= bit

        if not splitters:
            return current

        current |= splitters


def proper_edge_generated_modules(adj: list[int], component: int) -> list[int]:
    sizes: list[int] = []

    work_u = component
    while work_u:
        bit_u = work_u & -work_u
        u = bit_u.bit_length() - 1
        work_u -= bit_u

        neighbours = adj[u] & component
        neighbours &= ~((1 << (u + 1)) - 1)

        work_v = neighbours
        while work_v:
            bit_v = work_v & -work_v
            v = bit_v.bit_length() - 1
            work_v -= bit_v

            closure = minimal_module_closure(adj, u, v, component)
            if closure != component:
                sizes.append(closure.bit_count())

    return sizes


def upo_by_splitter_closure(adj: list[int]) -> bool:
    components = connected_components(adj)
    nontrivial = [c for c in components if c.bit_count() >= 2]

    if len(nontrivial) != 1:
        return False

    component = nontrivial[0]
    return not proper_edge_generated_modules(adj, component)


@dataclass
class DSU:
    parent: list[int]
    rank: list[int]

    @classmethod
    def make(cls, n: int) -> "DSU":
        return cls(list(range(n)), [0] * n)

    def find(self, x: int) -> int:
        while self.parent[x] != x:
            self.parent[x] = self.parent[self.parent[x]]
            x = self.parent[x]
        return x

    def union(self, a: int, b: int) -> None:
        a = self.find(a)
        b = self.find(b)
        if a == b:
            return
        if self.rank[a] < self.rank[b]:
            a, b = b, a
        self.parent[b] = a
        if self.rank[a] == self.rank[b]:
            self.rank[a] += 1


def implication_class_count(adj: list[int]) -> int:
    """Independent Gallai-forcing UPO classifier."""
    n = len(adj)
    edges: list[tuple[int, int]] = []
    index: dict[tuple[int, int], int] = {}

    for i in range(n):
        neighbours = adj[i] & ~((1 << (i + 1)) - 1)
        work = neighbours
        while work:
            bit = work & -work
            j = bit.bit_length() - 1
            work -= bit
            index[(i, j)] = len(edges)
            edges.append((i, j))

    if not edges:
        return 0

    dsu = DSU.make(len(edges))

    for v in range(n):
        neighbours = [u for u in range(n) if (adj[v] >> u) & 1]
        for ai in range(len(neighbours)):
            x = neighbours[ai]
            for bi in range(ai + 1, len(neighbours)):
                y = neighbours[bi]
                if not ((adj[x] >> y) & 1):
                    e1 = index[tuple(sorted((v, x)))]
                    e2 = index[tuple(sorted((v, y)))]
                    dsu.union(e1, e2)

    return len({dsu.find(i) for i in range(len(edges))})


def exact_random_2_order_regression(max_n: int) -> None:
    expected = {2: 1, 3: 4, 4: 12, 5: 38, 6: 165, 7: 1042}

    for n in range(2, max_n + 1):
        closure_count = 0
        implication_count = 0

        for p in itertools.permutations(range(n)):
            adj = permutation_graph(p)
            by_closure = upo_by_splitter_closure(adj)
            by_implication = implication_class_count(adj) == 1

            if by_closure:
                closure_count += 1
            if by_implication:
                implication_count += 1

            if by_closure != by_implication:
                raise AssertionError(
                    f"classifier disagreement at n={n}, permutation={p}"
                )

        if n in expected and closure_count != expected[n]:
            raise AssertionError(
                f"count mismatch at n={n}: got {closure_count}, expected {expected[n]}"
            )

        print(
            {
                "n": n,
                "closure_upo": closure_count,
                "implication_upo": implication_count,
            }
        )


def true_twin_count(adj: list[int]) -> int:
    groups: Counter[int] = Counter()
    for i, mask in enumerate(adj):
        groups[mask | (1 << i)] += 1
    return sum(k * (k - 1) // 2 for k in groups.values())


def run_cell(d: int, n: int, reps: int, seed: int) -> dict[str, object]:
    rng = np.random.default_rng(seed)

    categories = Counter()
    minimum_closure_sizes = Counter()

    for _ in range(reps):
        adj = comparability_masks(sprinkle_diamond(n, d, rng))
        components = connected_components(adj)
        nontrivial = [c for c in components if c.bit_count() >= 2]

        if not nontrivial:
            categories["empty"] += 1
            continue

        twins = true_twin_count(adj)

        if len(nontrivial) > 1:
            if twins:
                categories["multiple_components_with_twin"] += 1
            else:
                categories["multiple_components_without_twin"] += 1
            minimum_closure_sizes[
                ("component", min(c.bit_count() for c in nontrivial))
            ] += 1
            continue

        component = nontrivial[0]
        proper = proper_edge_generated_modules(adj, component)

        if not proper:
            categories["upo"] += 1
        elif twins:
            categories["internal_module_with_twin"] += 1
            minimum_closure_sizes[min(proper)] += 1
        else:
            categories["internal_module_without_twin"] += 1
            minimum_closure_sizes[min(proper)] += 1

    return {
        "d": d,
        "n": n,
        "reps": reps,
        "seed": seed,
        "categories": dict(categories),
        "minimum_closure_sizes": dict(minimum_closure_sizes),
    }


def parse_int_list(text: str) -> list[int]:
    return [int(x.strip()) for x in text.split(",") if x.strip()]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--regression-max-n", type=int, default=6)
    parser.add_argument("--skip-regression", action="store_true")
    parser.add_argument("--dims", default="4")
    parser.add_argument("--ns", default="32,48,64,96")
    parser.add_argument("--reps", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=20261120)
    args = parser.parse_args()

    if not args.skip_regression:
        exact_random_2_order_regression(args.regression_max_n)

    for d in parse_int_list(args.dims):
        for n in parse_int_list(args.ns):
            seed = args.seed + 1000003 * d + 1009 * n
            print(run_cell(d, n, args.reps, seed))


if __name__ == "__main__":
    main()
